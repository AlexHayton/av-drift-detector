"""Tests for version.py. Run with: python3 -m unittest discover -s scripts"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import version  # noqa: E402

SCRIPT = Path(__file__).resolve().parent / "version.py"
Version = version.Version


class VersionTests(unittest.TestCase):
    def test_spellings(self):
        for text, semver, pep440 in [
            ("1.2.3", "1.2.3", "1.2.3"),
            ("v0.1.0", "0.1.0", "0.1.0"),
            ("1.2.3-alpha.0", "1.2.3-alpha.0", "1.2.3a0"),
            ("1.2.3-rc.4", "1.2.3-rc.4", "1.2.3rc4"),
            ("1.2.3b2", "1.2.3-beta.2", "1.2.3b2"),
        ]:
            parsed = Version.parse(text)
            self.assertEqual((parsed.semver(), parsed.pep440()), (semver, pep440), text)

    def test_rejects_forms_the_registries_disagree_on(self):
        for text in ["1.2", "01.2.3", "1.2.3-pre.1", "1.2.3-rc", "1.2.3+build.5", "1.2.3.dev1", "1.2.3-RC.1"]:
            with self.assertRaises(version.Error, msg=text):
                Version.parse(text)

    def test_ordering(self):
        ordered = ["0.9.9", "1.0.0-alpha.1", "1.0.0-alpha.2", "1.0.0-alpha.10", "1.0.0-beta.1",
                   "1.0.0-rc.1", "1.0.0", "1.0.1", "1.1.0", "2.0.0"]
        keys = [Version.parse(text).key() for text in ordered]
        self.assertEqual(keys, sorted(keys))

    def test_bumps_follow_npm(self):
        for start, part, expected in [
            ("1.2.3", "patch", "1.2.4"),
            ("1.2.3", "minor", "1.3.0"),
            ("1.2.3", "major", "2.0.0"),
            ("1.0.0-rc.1", "patch", "1.0.0"),
            ("1.0.0-rc.1", "minor", "1.0.0"),
            ("1.0.0-rc.1", "major", "1.0.0"),
            ("1.2.0-rc.1", "minor", "1.2.0"),
            ("1.2.0-rc.1", "major", "2.0.0"),
            ("1.2.3-rc.1", "minor", "1.3.0"),
        ]:
            self.assertEqual(Version.parse(start).bumped(part).semver(), expected, f"{start} {part}")


def npm(name: str, version: str, **extra: object) -> str:
    return json.dumps({"name": name, "version": version, **extra}, indent=2) + "\n"


FIXTURE = {
    "Cargo.toml": '[package]\nname = "demo"\nversion = "0.1.0"\nedition = "2021"\n'
    'repository = "https://github.com/example/demo"\n\n[dependencies]\n',
    "Cargo.lock": "# This file is automatically @generated by Cargo.\n"
    "# It is not intended for manual editing.\nversion = 4\n\n"
    '[[package]]\nname = "demo"\nversion = "0.1.0"\n',
    "src/lib.rs": "",
    "CHANGELOG.md": "# Changelog\n\n## [Unreleased]\n\nFirst release.\n\n"
    "[Unreleased]: https://github.com/example/demo/commits/main\n",
    "docs/use.md": '```toml\ndemo = { version = "0.1", default-features = false }\n```\n',
    "bindings/ffi/Cargo.toml": '[package]\nname = "demo-ffi"\nversion = "0.0.0"\npublish = false\n\n'
    '[dependencies]\ndemo = { path = "../..", version = "0.1.0" }\n',
    "bindings/node/package.json": npm("demo", "0.1.0", optionalDependencies={"demo-darwin-arm64": "0.1.0"}),
    "bindings/node/package-lock.json": json.dumps(
        {"name": "demo", "version": "0.1.0", "lockfileVersion": 3,
         "packages": {"": {"name": "demo", "version": "0.1.0"}}}, indent=2) + "\n",
    "bindings/node/npm/darwin-arm64/package.json": npm("demo-darwin-arm64", "0.1.0"),
    "bindings/python/pyproject.toml": '[project]\nname = "demo"\nversion = "0.1.0"\n',
    "bindings/maturin/pyproject.toml": '[project]\nname = "demo-native"\ndynamic = ["version"]\n',
}


class RepositoryTests(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.root)
        for path, text in FIXTURE.items():
            self.write(path, text)
        self.git("init", "--quiet", "--initial-branch", "main")
        for key, value in [("user.name", "Test"), ("user.email", "test@example.com"),
                           ("commit.gpgsign", "false"), ("tag.gpgsign", "false")]:
            self.git("config", key, value)
        self.git("add", "--all")
        self.git("commit", "--quiet", "-m", "Initial")

    def write(self, path: str, text: str) -> None:
        (self.root / path).parent.mkdir(parents=True, exist_ok=True)
        (self.root / path).write_text(text)

    def read(self, path: str) -> str:
        return (self.root / path).read_text()

    def git(self, *args: str) -> str:
        return subprocess.run(["git", *args], cwd=self.root, check=True, capture_output=True,
                              text=True).stdout.strip()

    def run_script(self, *args: str, ok: bool = True) -> subprocess.CompletedProcess[str]:
        result = subprocess.run([sys.executable, str(SCRIPT), *args], cwd=self.root,
                                capture_output=True, text=True)
        self.assertEqual(result.returncode == 0, ok, result.stdout + result.stderr)
        return result

    def note(self, line: str) -> None:
        text = self.read("CHANGELOG.md").replace("## [Unreleased]\n\n", f"## [Unreleased]\n\n{line}\n\n", 1)
        self.write("CHANGELOG.md", text)

    def versions(self) -> dict[str, str]:
        node = json.loads(self.read("bindings/node/package.json"))
        lock = json.loads(self.read("bindings/node/package-lock.json"))
        return {
            "cargo": version.toml_string(self.read("Cargo.toml"), "version")[1],
            "lock": self.read("Cargo.lock").split('name = "demo"\nversion = "')[1].split('"')[0],
            "ffi-dep": self.read("bindings/ffi/Cargo.toml").split('version = "')[2].split('"')[0],
            "docs": self.read("docs/use.md").split('version = "')[1].split('"')[0],
            "node": node["version"],
            "node-dep": node["optionalDependencies"]["demo-darwin-arm64"],
            "node-lock": f'{lock["version"]} {lock["packages"][""]["version"]}',
            "node-platform": json.loads(self.read("bindings/node/npm/darwin-arm64/package.json"))["version"],
            "python": version.toml_string(self.read("bindings/python/pyproject.toml"), "version")[1],
        }

    def test_release_sequence(self):
        self.assertIn("0.1.0: 4 manifest(s) agree", self.run_script("check").stdout)

        # The first release keeps the version and dates the changelog.
        self.run_script("bump", "0.1.0", "--date", "2026-01-02")
        self.assertEqual(self.git("tag", "--list"), "v0.1.0")
        changelog = self.read("CHANGELOG.md")
        self.assertIn("## [Unreleased]\n\n## [0.1.0] - 2026-01-02\n\nFirst release.\n\n[Unreleased]:", changelog)
        self.assertIn("[Unreleased]: https://github.com/example/demo/compare/v0.1.0...HEAD\n"
                      "[0.1.0]: https://github.com/example/demo/releases/tag/v0.1.0\n", changelog)
        self.assertEqual(self.run_script("notes", "v0.1.0").stdout.strip(), "First release.")
        self.assertIn("is empty", self.run_script("bump", "minor", ok=False).stderr)

        # Uncommitted changelog notes are fine; everything moves together.
        self.note("- Something new.")
        self.run_script("bump", "minor", "--date", "2026-02-03")
        self.assertEqual(self.versions(), {
            "cargo": "0.2.0", "lock": "0.2.0", "ffi-dep": "0.2.0", "docs": "0.2", "node": "0.2.0",
            "node-dep": "0.2.0", "node-lock": "0.2.0 0.2.0", "node-platform": "0.2.0", "python": "0.2.0",
        })
        self.assertEqual(self.git("log", "-1", "--format=%s"), "Release v0.2.0")
        self.assertEqual(self.git("status", "--porcelain"), "")
        self.assertIn("[0.2.0]: https://github.com/example/demo/compare/v0.1.0...v0.2.0\n"
                      "[0.1.0]:", self.read("CHANGELOG.md"))
        self.assertIn('dynamic = ["version"]', self.read("bindings/maturin/pyproject.toml"))
        self.assertIn('name = "demo-ffi"\nversion = "0.0.0"', self.read("bindings/ffi/Cargo.toml"))

        # Pre-releases use PEP 440 for Python and leave the docs alone.
        self.note("- Getting ready.")
        self.run_script("bump", "1.0.0-rc.1")
        found = self.versions()
        self.assertEqual((found["cargo"], found["python"], found["docs"]), ("1.0.0-rc.1", "1.0.0rc1", "0.2"))
        self.run_script("check", "--tag", "v1.0.0-rc.1")
        self.assertIn("doesn't match", self.run_script("check", "--tag", "v1.0.0", ok=False).stderr)

        # A dry run reports and writes nothing.
        self.note("- Done.")
        before = {path: self.read(path) for path in FIXTURE}
        self.assertIn("1.0.0-rc.1 -> 1.0.0", self.run_script("bump", "patch", "--dry-run").stdout)
        self.assertEqual({path: self.read(path) for path in FIXTURE}, before)

    def test_virtual_workspace(self):
        # The crate in a subdirectory, sharing the workspace's repository URL.
        self.write("crates/demo/Cargo.toml", '[package]\nname = "demo"\nversion = "0.1.0"\n'
                   'edition = "2021"\nrepository.workspace = true\n')
        self.write("crates/demo/src/lib.rs", "")
        self.write("Cargo.toml", '[workspace]\nmembers = ["crates/demo"]\n\n'
                   '[workspace.package]\nrepository = "https://github.com/example/demo"\n')
        self.git("rm", "--quiet", "src/lib.rs")
        self.git("add", "--all")
        self.git("commit", "--quiet", "-m", "Workspace")
        self.assertIn("0.1.0: 4 manifest(s) agree", self.run_script("check").stdout)

        self.run_script("bump", "0.1.0", "--date", "2026-01-02")
        self.assertIn("[0.1.0]: https://github.com/example/demo/releases/tag/v0.1.0\n", self.read("CHANGELOG.md"))
        self.note("- More.")
        self.run_script("bump", "minor", "--date", "2026-02-03")
        self.assertIn('name = "demo"\nversion = "0.2.0"', self.read("crates/demo/Cargo.toml"))
        self.assertIn("[0.2.0]: https://github.com/example/demo/compare/v0.1.0...v0.2.0\n", self.read("CHANGELOG.md"))

    def test_refusals(self):
        self.assertIn("older", self.run_script("bump", "0.0.9", ok=False).stderr)
        self.assertIn("not a supported version", self.run_script("bump", "0.2", ok=False).stderr)

        self.write("src/lib.rs", "// edited\n")
        self.assertIn("commit or stash", self.run_script("bump", "patch", ok=False).stderr)
        self.git("checkout", "--", "src/lib.rs")

        self.git("switch", "--quiet", "--create", "feature")
        self.assertIn("releases are made from main", self.run_script("bump", "patch", ok=False).stderr)
        self.git("switch", "--quiet", "main")

        self.git("tag", "v0.1.1")
        self.assertIn("already exists", self.run_script("bump", "patch", ok=False).stderr)

        self.write("bindings/python/pyproject.toml", '[project]\nname = "demo"\nversion = "0.1.1"\n')
        self.assertIn("disagree", self.run_script("check", ok=False).stderr)


if __name__ == "__main__":
    unittest.main()
